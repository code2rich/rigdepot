// brandNames is the content of brand.json, the single source of every name
// the code uses. A fork that has to rename the product edits that one file
// and regenerates.
type brandNames struct {
	Name          string `json:"name"`
	CLI           string `json:"cli"`
	CLILong       string `json:"cliLong"`
	Server        string `json:"server"`
	Home          string `json:"home"`
	Prefix        string `json:"prefix"`
	ManagedMarker string `json:"managedMarker"`
	MCPEntry      string `json:"mcpEntry"`
	RepoConfig    string `json:"repoConfig"`
	EnvPrefix     string `json:"envPrefix"`
}

// brandFields lists the constants in the order they are generated, each with
// its key in brand.json and its documentation.
func (b brandNames) fields() []struct{ name, key, value, doc string } {
	return []struct{ name, key, value, doc string }{
		{"Name", "name", b.Name, "the product name."},
		{"CLI", "cli", b.CLI, "the name of the command-line program, as typed."},
		{"CLILong", "cliLong", b.CLILong, "the long name of the command-line program, used for packages."},
		{"Server", "server", b.Server, "the name of the server program."},
		{"Home", "home", b.Home, "the name of the local data directory inside the user's home directory."},
		{"Prefix", "prefix", b.Prefix, "the prefix of every entry written into another tool's configuration."},
		{"ManagedMarker", "managedMarker", b.ManagedMarker, "the marker left in files this product manages."},
		{"MCPEntry", "mcpEntry", b.MCPEntry, "the name of the single-entry MCP server."},
		{"RepoConfig", "repoConfig", b.RepoConfig, "the file name of a resource repository's configuration."},
		{"EnvPrefix", "envPrefix", b.EnvPrefix, "the prefix of every environment variable the programs read."},
	}
}

const brandFile = "brand.json"

func readBrand(root string) (brandNames, error) {
	var b brandNames
	data, err := os.ReadFile(filepath.Join(root, brandFile))
	if err != nil {
		return b, err
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields() // a new name needs a constant: add it to brandNames
	if err := dec.Decode(&b); err != nil {
		return b, fmt.Errorf("%s: %w", brandFile, err)
	}
	for _, f := range b.fields() {
		if f.value == "" {
			return b, fmt.Errorf("%s: the value for %s is missing or empty", brandFile, f.name)
		}
	}
	return b, nil
}

// generated is one generated file: its path relative to the repository root
// and its content.
type generated struct {
	path string
	data []byte
}

// generate computes every generated file without touching the disk. env is
// the environment of the code generators it runs; nil means this process's.
// skipped lists the files this machine cannot generate (the API types of
// the web console without Node): they are reported as not run.
func generate(root string, env []string) (files []generated, skipped []webSkipped, err error) {
	b, err := readBrand(root)
	if err != nil {
		return nil, nil, err
	}
	src, err := brandGo(b)
	if err != nil {
		return nil, nil, err
	}
	files = []generated{{path: "internal/brand/brand_gen.go", data: src}}
	messages, err := generateMessages(root)
	if err != nil {
		return nil, nil, err
	}
	files = append(files, messages...)
	kinds, err := generateKindSchemas(root)
	if err != nil {
		return nil, nil, err
	}
	files = append(files, kinds...)
	api, err := generateAPI(root, env)
	if err != nil {
		return nil, nil, err
	}
	files = append(files, api...)
	web, skipped, err := generateWeb(root, env, b)
	if err != nil {
		return nil, nil, err
	}
	return append(files, web...), skipped, nil
}

func brandGo(b brandNames) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by \"go run ./tools/dev gen\" from brand.json. DO NOT EDIT.\n\n")
	buf.WriteString("package brand\n\nconst (\n")
	for _, f := range b.fields() {
		fmt.Fprintf(&buf, "\t// %s is %s\n\t%s = %q\n", f.name, f.doc, f.name, f.value)
	}
	buf.WriteString(")\n")
	return format.Source(buf.Bytes())
}

// runGen writes the generated files, or with --check only reports the ones
// that differ from what is on disk.
func runGen(root string, args []string) error {
	check := false
	for _, a := range args {
		switch a {
		case "--check", "-check":
			check = true
		default:
			return fmt.Errorf("unknown argument %q (the only option is --check)", a)
		}
	}
	_, err := gen(root, nil, check)
	return err
}

// gen regenerates everything with the code generators running in env (nil:
// this process's environment) and writes the result, or with check only
// reports what is out of date. A file this machine cannot generate is
// printed as not run and returned in skipped; it never counts as up to
// date.
func gen(root string, env []string, check bool) (skipped []webSkipped, err error) {
	files, skipped, err := generate(root, env)
	if err != nil {
		return nil, err
	}
	for _, s := range skipped {
		fmt.Printf("not run: %s (%s)\n", s.path, s.reason)
	}
	stale := staleFiles(root, files)
	if check {
		if len(stale) > 0 {
			return skipped, fmt.Errorf("generated files are out of date: %s\nrun: go run ./tools/dev gen", strings.Join(stale, ", "))
		}
		return skipped, nil
	}
	for _, f := range files {
		path := filepath.Join(root, filepath.FromSlash(f.path))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return skipped, err
		}
		if err := os.WriteFile(path, f.data, 0o644); err != nil {
			return skipped, err
		}
	}
	for _, p := range stale {
		fmt.Println("wrote", p)
	}
	return skipped, nil
}

// staleFiles returns the generated files whose content on disk differs. A
// file that cannot be read counts as stale.
func staleFiles(root string, files []generated) []string {
	var stale []string
	for _, f := range files {
		onDisk, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(f.path)))
		if err != nil || !bytes.Equal(onDisk, f.data) {
			stale = append(stale, f.path)
		}
	}
	return stale
}

// kindSchemaDir is where the schema of every built-in resource kind is
// collected for publishing, next to the other schemas of the repository
// format. The original is builtin/kinds/<kind>/schema.json, which the kind
// embeds and returns from Schema().
const kindSchemaDir = "schema/repo/v1/kinds"

// generateKindSchemas copies each kind's schema to
// schema/repo/v1/kinds/<kind>.schema.json, byte for byte. The schema's $id has
// to be the address of that copy, so that what a resource author's editor
// fetches is the schema the programs validate with.
func generateKindSchemas(root string) ([]generated, error) {
	sources, err := filepath.Glob(filepath.Join(root, "builtin", "kinds", "*", "schema.json"))
	if err != nil {
		return nil, err
	}
	var out []generated
	for _, src := range sources {
		data, err := os.ReadFile(src)
		if err != nil {
			return nil, err
		}
		name := filepath.Base(filepath.Dir(src))
		rel := kindSchemaDir + "/" + name + ".schema.json"
		var doc struct {
			ID string `json:"$id"`
		}
		if err := json.Unmarshal(data, &doc); err != nil {
			return nil, fmt.Errorf("builtin/kinds/%s/schema.json: %w", name, err)
		}
		if !strings.HasSuffix(doc.ID, "/"+strings.TrimPrefix(rel, "schema/")) {
			return nil, fmt.Errorf("builtin/kinds/%s/schema.json: $id is %q; it has to end with /%s, where the schema is published",
				name, doc.ID, strings.TrimPrefix(rel, "schema/"))
		}
		out = append(out, generated{path: rel, data: data})
	}
	return out, nil
}
