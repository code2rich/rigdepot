// releaseFilesDir holds what the release archives carry besides the programs, the license and
// NOTICE: shell completions and the third-party notices. It is build output inside the ignored
// local state directory; .goreleaser.yaml picks the files up from there.
const releaseFilesDir = ".dev/release"

// completionFiles maps each shell to the file name its completion script gets in the archive.
// The Homebrew cask in .goreleaser.yaml installs the first three from these paths.
var completionFiles = []struct{ shell, file string }{
	{"bash", "%s.bash"},
	{"zsh", "_%s"},
	{"fish", "%s.fish"},
	{"powershell", "%s.ps1"},
}

// runReleaseFiles writes releaseFilesDir. goreleaser runs it as a hook before it builds, so a
// release cannot ship completions or notices from an older commit.
func runReleaseFiles(root string, args []string) error {
	if len(args) != 0 {
		return errors.New("release-files takes no arguments")
	}
	b, err := readBrand(root)
	if err != nil {
		return err
	}
	dir := filepath.Join(root, filepath.FromSlash(releaseFilesDir))
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(dir, "completions"), 0o755); err != nil {
		return err
	}
	if err := writeCompletions(root, b, filepath.Join(dir, "completions")); err != nil {
		return fmt.Errorf("completions: %w", err)
	}
	notices, err := thirdPartyNotices(root, b)
	if err != nil {
		return fmt.Errorf("third-party notices: %w", err)
	}
	if err := os.WriteFile(filepath.Join(dir, "THIRD_PARTY_NOTICES"), notices, 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s: completions for %d shells, THIRD_PARTY_NOTICES\n", releaseFilesDir, len(completionFiles))
	return nil
}

// writeCompletions builds the command-line program for this machine and has it print its
// completion scripts. It runs in a temporary home, in English: a script must not depend on the
// configuration or the language of whoever builds the release, or two builds would differ.
func writeCompletions(root string, b brandNames, dir string) error {
	tmp, err := os.MkdirTemp("", "release-files-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tmp)
	exe := filepath.Join(tmp, b.CLI)
	if filepath.Separator == '\\' {
		exe += ".exe"
	}
	if _, err := output(root, nil, "go", "build", "-trimpath", "-o", exe, "./cmd/"+b.CLI); err != nil {
		return err
	}
	env := mergeEnv(withoutPrefix(os.Environ(), b.EnvPrefix), map[string]string{
		"HOME":                         tmp,
		"USERPROFILE":                  tmp,
		"XDG_CONFIG_HOME":              filepath.Join(tmp, ".config"),
		"APPDATA":                      filepath.Join(tmp, "AppData", "Roaming"),
		"LOCALAPPDATA":                 filepath.Join(tmp, "AppData", "Local"),
		b.EnvPrefix + "LANG":           "en",
		"LANG":                         "C",
		"LC_ALL":                       "C",
		"NO_COLOR":                     "1",
		b.EnvPrefix + "HOME":           filepath.Join(tmp, b.Home),
		b.EnvPrefix + "NONINTERACTIVE": "1",
	})
	for _, c := range completionFiles {
		script, err := output(tmp, env, exe, "completion", c.shell)
		if err != nil {
			return err
		}
		name := fmt.Sprintf(c.file, b.CLI)
		if err := os.WriteFile(filepath.Join(dir, name), []byte(script+"\n"), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// withoutPrefix drops the variables whose names start with prefix.
func withoutPrefix(env []string, prefix string) []string {
	var out []string
	for _, kv := range env {
		if !strings.HasPrefix(strings.ToUpper(kv), prefix) {
			out = append(out, kv)
		}
	}
	return out
}

// thirdPartyModule is a Go module compiled into a release program.
type thirdPartyModule struct {
	path, version, dir string
}

// thirdPartyNotices lists every module linked into the two programs on any of their release
// targets, with the license and notice texts the module ships. A module whose license is not on
// the allowed list (docs: licensing, 10-release "第三方声明"), or cannot be recognised, stops the
// release: someone has to look at it.
func thirdPartyNotices(root string, b brandNames) ([]byte, error) {
	modules, err := linkedModules(root, b)
	if err != nil {
		return nil, err
	}
	var out strings.Builder
	out.WriteString("Third-party software in " + b.CLI + " and " + b.Server + "\n\n")
	out.WriteString("These Go modules are compiled into the release programs. Each is listed with\n")
	out.WriteString("the license and notice files it ships. The web console's own dependencies\n")
	out.WriteString("and fonts are listed in NOTICE.\n")
	out.WriteString("Generated by \"go run ./tools/dev release-files\"; do not edit.\n")
	var problems []string
	for _, m := range modules {
		files, err := licenseFiles(m.dir)
		if err != nil {
			return nil, err
		}
		if len(files) == 0 {
			problems = append(problems, m.path+": no license file")
			continue
		}
		var texts []string
		var kinds []string
		for _, f := range files {
			data, err := os.ReadFile(filepath.Join(m.dir, f))
			if err != nil {
				return nil, err
			}
			texts = append(texts, "--- "+f+"\n\n"+strings.TrimRight(strings.ReplaceAll(string(data), "\r\n", "\n"), "\n")+"\n")
			if isNoticeFile(f) {
				continue
			}
			found, forbidden := classifyLicense(string(data))
			if len(forbidden) > 0 {
				problems = append(problems, fmt.Sprintf("%s: %s is %s, which is not allowed", m.path, f, strings.Join(forbidden, ", ")))
			}
			kinds = append(kinds, found...)
		}
		slices.Sort(kinds)
		kinds = slices.Compact(kinds)
		if len(kinds) == 0 {
			problems = append(problems, m.path+": the license could not be recognised; check it by hand and teach classifyLicense")
		}
		fmt.Fprintf(&out, "\n%s\n%s %s\nLicense: %s\n\n%s", strings.Repeat("=", 72), m.path, m.version, strings.Join(kinds, ", "), strings.Join(texts, "\n"))
	}
	if len(problems) > 0 {
		return nil, fmt.Errorf("%d module(s) need a look:\n  %s", len(problems), strings.Join(problems, "\n  "))
	}
	return []byte(out.String()), nil
}

// linkedModules returns the third-party modules of both programs over all their release
// targets, sorted by path.
func linkedModules(root string, b brandNames) ([]thirdPartyModule, error) {
	type build struct{ pkg, os, arch string }
	var builds []build
	for _, t := range targets {
		builds = append(builds, build{"./cmd/" + b.CLI, t.os, t.arch})
		if t.os == "linux" {
			builds = append(builds, build{"./cmd/" + b.Server, t.os, t.arch})
		}
	}
	seen := map[string]thirdPartyModule{}
	for _, bd := range builds {
		env := mergeEnv(os.Environ(), map[string]string{"GOOS": bd.os, "GOARCH": bd.arch, "CGO_ENABLED": "0"})
		out, err := output(root, env, "go", "list", "-deps", "-f",
			"{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}", bd.pkg)
		if err != nil {
			return nil, err
		}
		for _, line := range strings.Split(out, "\n") {
			parts := strings.Split(line, "\t")
			if len(parts) != 3 {
				continue
			}
			if parts[2] == "" {
				return nil, fmt.Errorf("%s %s is not in the module cache; run: go run ./tools/dev deps", parts[0], parts[1])
			}
			seen[parts[0]+"@"+parts[1]] = thirdPartyModule{parts[0], parts[1], parts[2]}
		}
	}
	modules := make([]thirdPartyModule, 0, len(seen))
	for _, m := range seen {
		modules = append(modules, m)
	}
	sort.Slice(modules, func(i, j int) bool {
		if modules[i].path != modules[j].path {
			return modules[i].path < modules[j].path
		}
		return modules[i].version < modules[j].version
	})
	return modules, nil
}

var licenseFileName = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents)([._-].*)?$`)

// licenseFiles returns the license, notice and patent grant files at the top of a module.
func licenseFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range entries {
		if e.Type().IsRegular() && licenseFileName.MatchString(e.Name()) {
			out = append(out, e.Name())
		}
	}
	sort.Strings(out)
	return out, nil
}

// isNoticeFile reports whether a file is carried along but not classified: notices, patent
// grants, and a module's own account of the code of others it contains (modernc.org/sqlite's
// LICENSE-3RD-PARTY.md quotes licenses, the MPL among them, of components that are only in its
// tests or its module graph and are not compiled into anything).
func isNoticeFile(name string) bool {
	n := strings.ToLower(name)
	return strings.HasPrefix(n, "notice") || strings.HasPrefix(n, "patents") ||
		strings.Contains(n, "3rd-party") || strings.Contains(n, "third-party") || strings.Contains(n, "third_party")
}

// licenseKinds recognise a license text by phrases it always contains (every phrase of an entry
// must be there). The forbidden ones are checked as well, so that a file holding two licenses
// cannot slip one through.
var licenseKinds = []struct {
	id      string
	allowed bool
	phrases []string
}{
	{"GPL", false, []string{"gnu general public license"}},
	{"LGPL", false, []string{"gnu lesser general public license"}},
	{"AGPL", false, []string{"gnu affero general public license"}},
	{"SSPL", false, []string{"server side public license"}},
	{"BUSL", false, []string{"business source license"}},
	{"Apache-2.0", true, []string{"apache license", "version 2.0"}},
	{"MIT", true, []string{"permission is hereby granted, free of charge"}},
	{"BSD", true, []string{"redistribution and use in source and binary forms"}},
	{"ISC", true, []string{"permission to use, copy, modify, and", "for any purpose with or without fee"}},
	{"OFL-1.1", true, []string{"sil open font license"}},
}

var spaces = regexp.MustCompile(`\s+`)

// classifyLicense returns the allowed and the forbidden licenses a text contains.
func classifyLicense(text string) (allowed, forbidden []string) {
	norm := spaces.ReplaceAllString(strings.ToLower(text), " ")
	for _, k := range licenseKinds {
		all := true
		for _, p := range k.phrases {
			if !strings.Contains(norm, p) {
				all = false
				break
			}
		}
		if !all {
			continue
		}
		if k.allowed {
			allowed = append(allowed, k.id)
		} else {
			forbidden = append(forbidden, k.id)
		}
	}
	return allowed, forbidden
}
